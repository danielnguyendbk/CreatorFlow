import type { Content, StageProgress, WorkflowStage } from '@/types';

const makeStages = (
  completedUpTo: WorkflowStage,
  current: WorkflowStage,
  hasError?: boolean,
): StageProgress[] => {
  const order: WorkflowStage[] = [
    'IDEA',
    'SCRIPT',
    'STORYBOARD',
    'VOICE',
    'VISUAL_ASSETS',
    'RENDER',
    'SUBTITLE',
    'PUBLICATION',
  ];

  return order.map((stage) => {
    const idx = order.indexOf(stage);
    const currentIdx = order.indexOf(current);
    const completedIdx = order.indexOf(completedUpTo);

    if (idx < completedIdx) {
      return {
        stage,
        status: 'COMPLETED',
        startedAt: '2026-09-18T08:00:00Z',
        completedAt: '2026-09-18T09:00:00Z',
        error: null,
        retryCount: 0,
      };
    }
    if (idx === currentIdx && hasError) {
      return {
        stage,
        status: 'FAILED',
        startedAt: '2026-09-18T10:00:00Z',
        completedAt: null,
        error: 'FFmpeg exited with code 1: Invalid codec parameters',
        retryCount: 2,
      };
    }
    if (idx === currentIdx) {
      return {
        stage,
        status: 'IN_PROGRESS',
        startedAt: '2026-09-19T08:00:00Z',
        completedAt: null,
        error: null,
        retryCount: 0,
      };
    }
    return {
      stage,
      status: 'PENDING',
      startedAt: null,
      completedAt: null,
      error: null,
      retryCount: 0,
    };
  });
};

